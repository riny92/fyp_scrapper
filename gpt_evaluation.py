import os
import json
from openai import OpenAI
from dotenv import load_dotenv

load_dotenv()


client = OpenAI()

DATASET_FOLDER = "."

def list_datasets():
    datasets = [f for f in os.listdir(DATASET_FOLDER) if f.endswith('.json')]
    if not datasets:
        print("No datasets found.")
        return None
    print("\nAvailable Datasets:")
    for idx, dataset in enumerate(datasets, 1):
        print(f"{idx}. {dataset}")
    while True:
        try:
            choice = int(input("\nSelect a dataset by number: ")) - 1
            if 0 <= choice < len(datasets):
                return os.path.join(DATASET_FOLDER, datasets[choice])
            else:
                print("Invalid selection. Try again.")
        except ValueError:
            print("Enter a valid number.")

def query_gpt(text):
    prompt = (
        "You will be shown a paragraph of academic text. "
        "Based on your understanding, determine whether the text was written by a human or generated by an AI. "
        "Reply strictly with one of the two labels only: HUMAN or AI. Do not add any explanation or extra characters.\n\n"
        f"Text:\n{text.strip()}"
    )
    try:
        response = client.chat.completions.create(
            model="gpt-4o",
            messages=[
                {"role": "system", "content": "You are a text classification assistant."},
                {"role": "user", "content": prompt}
            ],
            
            temperature=0
        )
        return response.choices[0].message.content.strip().upper()
    except Exception as e:
        print("Error during GPT call:", e)
        return "ERROR"

def run_gpt_evaluation(dataset_path):
    with open(dataset_path, "r", encoding="utf-8") as file:
        data = json.load(file)

    correct_human = 0
    correct_ai = 0
    total_human = 0
    total_ai = 0

    for paper_id, paragraphs in data.items():
        for para in paragraphs:
            if para.get("multilinear", 1) != 0:
                continue
            human_texts = para.get("human", [])
            ai_texts = para.get("ai", [])
            if human_texts:
                total_human += 1
                label = query_gpt(human_texts[0])
                if label == "HUMAN":
                    correct_human += 1
            if ai_texts:
                total_ai += 1
                label = query_gpt(ai_texts[0])
                if label == "AI":
                    correct_ai += 1

    print("\n--- GPT Evaluation Summary ---")
    print(f"Human paragraphs correctly identified: {correct_human} / {total_human}")
    print(f"AI paragraphs correctly identified:    {correct_ai} / {total_ai}")

def main():
    dataset_path = list_datasets()
    if not dataset_path:
        return
    print(f"\nLoading {dataset_path} ...")
    run_gpt_evaluation(dataset_path)

if __name__ == "__main__":
    main()
